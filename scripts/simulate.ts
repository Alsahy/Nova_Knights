/**
 * simulate (lane E, PLAN Phase 5).
 *   npm run sim -- --mission M3 --seed 42 --verbose                 one bot, readable log
 *   npm run sim -- --report --games 1000 --seed-start 1             balance report for all bots
 * The report writes docs/balance-report.md, docs/balance-report.json and two SVG charts in docs/charts/.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ALL_BOTS } from '../src/sim/bots';
import { missionReport, runSim, type MissionReport } from '../src/sim/run';
import type { MissionId, Tier } from '../src/engine/types';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const get = (k: string, d: string): string => {
  const i = args.indexOf(`--${k}`);
  return i >= 0 && args[i + 1] && !args[i + 1]!.startsWith('--') ? args[i + 1]! : d;
};

const pct = (n: number, d: number) => `${Math.round((100 * n) / d)}%`;
const BOT_LABEL: Record<string, string> = {
  random: 'Random',
  maxShield: 'Max shield',
  maxScience: 'Max science (never repairs)',
  balanced: 'Balanced',
  bestMove: 'Best move (lookahead)',
};

/** A single-series horizontal bar chart as a static SVG (for slides). */
function barChart(
  title: string,
  rows: { label: string; value: number; text: string }[],
  max: number,
): string {
  const W = 760;
  const rowH = 44;
  const left = 250;
  const right = 70;
  const top = 64;
  const H = top + rows.length * rowH + 40;
  const bw = W - left - right;
  const esc = (t: string) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;');
  const ticks = [0, 0.25, 0.5, 0.75, 1].map((f) => f * max);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="${esc(title)}" font-family="Atkinson Hyperlegible, system-ui, sans-serif">
  <rect width="${W}" height="${H}" fill="#ffffff"/>
  <text x="24" y="36" font-size="20" font-weight="700" fill="#1b1b2f">${esc(title)}</text>
${ticks
  .map((t) => {
    const x = left + (bw * t) / max;
    return `  <line x1="${x}" y1="${top - 6}" x2="${x}" y2="${top + rows.length * rowH}" stroke="#e3e1dc" stroke-width="1"/>
  <text x="${x}" y="${top + rows.length * rowH + 22}" font-size="13" fill="#5a5a6e" text-anchor="middle">${Math.round(t)}${max === 100 ? '%' : ''}</text>`;
  })
  .join('\n')}
${rows
  .map((r, i) => {
    const y = top + i * rowH + 8;
    const w = Math.max(2, (bw * r.value) / max);
    return `  <text x="${left - 12}" y="${y + 20}" font-size="15" fill="#1b1b2f" text-anchor="end">${esc(r.label)}</text>
  <path d="M${left} ${y} h${w - 4} a4 4 0 0 1 4 4 v20 a4 4 0 0 1 -4 4 h-${w - 4} z" fill="#2a6fb0"/>
  <text x="${left + w + 8}" y="${y + 19}" font-size="15" font-weight="700" fill="#1b1b2f">${esc(r.text)}</text>`;
  })
  .join('\n')}
</svg>
`;
}

function reportMd(reports: MissionReport[], games: number, seedStart: number): string {
  const lines: string[] = [];
  lines.push('# Balance report', '');
  lines.push(
    `*Generated by \`npm run sim -- --report --games ${games} --seed-start ${seedStart}\`. Kid scope (D-018…D-025), Cadet, all numbers from \`src/engine/config.ts\`.*`,
    '',
  );
  lines.push(
    'Targets in spec §1.4: no strategy wins more than 80 % · balanced play wins 60–75 % · pure greed (max-science, never repairs) loses most games · 70 % of the deck appears across 100 games · no two games identical · every card is the best pick somewhere. **P-007 asks the lead whether these targets still fit the kid game.**',
    '',
  );
  for (const r of reports) {
    lines.push(`## ${r.mission} · ${r.tier}`, '');
    lines.push(
      '| Strategy | Mission Success | Safe Return | Brought home | Avg stars sent | Avg badge | Badge red | Events per game (min–max) | Ending reasons |',
    );
    lines.push('|---|---|---|---|---|---|---|---|---|');
    for (const b of r.bots) {
      const reasons = Object.entries(b.reasons)
        .sort((a, c) => c[1] - a[1])
        .map(([k, v]) => `${k.replace('end.', '')} ${pct(v, b.games)}`)
        .join(', ');
      lines.push(
        `| ${BOT_LABEL[b.bot] ?? b.bot} | **${pct(b.success, b.games)}** | ${pct(b.safeReturn, b.games)} | ${pct(b.broughtHome, b.games)} | ${b.avgSpBanked.toFixed(1)} | ${b.avgDose.toFixed(1)} | ${pct(b.redBadgeRate * b.games, b.games)} | ${b.avgEvents.toFixed(1)} (${b.minEvents}–${b.maxEvents}) | ${reasons} |`,
      );
    }
    lines.push('');
    lines.push(
      `- **Variety:** ${r.variety.seenEvents} of ${r.variety.deckEvents} scope events appeared across ${r.variety.games} random games (${r.variety.pct} %); ${r.variety.uniqueLists} different event lists out of ${r.variety.games}.`,
    );
    lines.push(
      `- **Card coverage (best-move bot):** ${r.coverage.chosen} of ${r.coverage.cards} Cadet cards chosen at least once${r.coverage.missing.length ? `; never chosen: ${r.coverage.missing.join(', ')}` : ''}.`,
    );
    lines.push(
      `- **No free lunch (static):** ${r.noFreeLunch.withCost} of ${r.noFreeLunch.cards} cards in scope have a cost${r.noFreeLunch.missing.length ? `; missing: ${r.noFreeLunch.missing.join(', ')}` : ''}.`,
    );
    lines.push('');
  }
  lines.push(
    '## Charts',
    '',
    '![Mission Success by strategy](charts/winrate.svg)',
    '',
    '![Average radiation badge by strategy](charts/dose.svg)',
    '',
  );
  return lines.join('\n');
}

if (args.includes('--report')) {
  const games = Number(get('games', '1000'));
  const seedStart = Number(get('seed-start', '1'));
  const tier = get('tier', 'cadet') as Tier;
  const missions = get('mission', 'M3,M1').split(',') as MissionId[];
  const bots =
    get('bot', 'all') === 'all'
      ? ALL_BOTS
      : (get('bot', 'random').split(',') as unknown as typeof ALL_BOTS);
  const t0 = Date.now();
  const reports = missions.map((m) => missionReport(m, tier, games, seedStart, bots));
  mkdirSync(resolve(ROOT, 'docs/charts'), { recursive: true });
  writeFileSync(resolve(ROOT, 'docs/balance-report.md'), reportMd(reports, games, seedStart));
  writeFileSync(
    resolve(ROOT, 'docs/balance-report.json'),
    JSON.stringify({ games, seedStart, reports }, null, 1) + '\n',
  );
  const main = reports[0]!;
  writeFileSync(
    resolve(ROOT, 'docs/charts/winrate.svg'),
    barChart(
      `Mission Success by strategy (${main.mission}, ${games} games each)`,
      main.bots.map((b) => ({
        label: BOT_LABEL[b.bot] ?? b.bot,
        value: (100 * b.success) / b.games,
        text: pct(b.success, b.games),
      })),
      100,
    ),
  );
  writeFileSync(
    resolve(ROOT, 'docs/charts/dose.svg'),
    barChart(
      `Average radiation badge at the end (${main.mission}, red at 7)`,
      main.bots.map((b) => ({
        label: BOT_LABEL[b.bot] ?? b.bot,
        value: b.avgDose,
        text: b.avgDose.toFixed(1),
      })),
      10,
    ),
  );
  console.log(reportMd(reports, games, seedStart));
  console.log(`(${((Date.now() - t0) / 1000).toFixed(1)} s)`);
} else {
  const lines = runSim({
    mission: get('mission', 'M3') as MissionId,
    tier: get('tier', 'cadet') as Tier,
    seed: Number(get('seed', '42')),
    games: Number(get('games', '1')),
    bot: get('bot', 'random'),
    verbose: args.includes('--verbose'),
  });
  console.log(lines.join('\n'));
}
